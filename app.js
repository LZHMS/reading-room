  var PER_PAGE = 10;

  function pageOf(s) {
    var n = parseInt(s, 10);
    return (isFinite(n) && n >= 1) ? n : 1;
  }

  function clampPage(page, total) {
    var pages = Math.max(1, Math.ceil(total / PER_PAGE));
    return Math.min(Math.max(1, page), pages);
  }

  function pagerHtml(page, total, hrefOf) {
    var pages = Math.ceil(total / PER_PAGE);
    if (pages <= 1) return '';
    var nums = [];
    for (var i = 1; i <= pages; i++) {
      if (i === 1 || i === pages || Math.abs(i - page) <= 1) nums.push(i);
      else if (nums[nums.length - 1] !== -1) nums.push(-1);
    }
    var html = '<div class="pager">';
    html += page > 1
      ? '<a class="pager-btn" href="' + hrefOf(page - 1) + '">← 上一页</a>'
      : '<span class="pager-btn off">← 上一页</span>';
    nums.forEach(function (n) {
      if (n === -1) { html += '<span class="pager-ellipsis">…</span>'; return; }
      html += n === page
        ? '<span class="pager-num cur">' + n + '</span>'
        : '<a class="pager-num" href="' + hrefOf(n) + '">' + n + '</a>';
    });
    html += page < pages
      ? '<a class="pager-btn" href="' + hrefOf(page + 1) + '">下一页 →</a>'
      : '<span class="pager-btn off">下一页 →</span>';
    return html + '</div>';
  }

