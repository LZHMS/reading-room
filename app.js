  function inline(s) {
    s = esc(s);
    s = s.replace(/!\[([^\]]*)\]\(([^)\s]+)[^)]*\)/g, function (_, alt, url) {
      return '<img src="' + url + '" alt="' + alt + '" loading="lazy">';
    });
    s = s.replace(/\[([^\]]+)\]\(([^)\s]+)(?:\s+&quot;[^&]*&quot;)?\)/g, function (_, tt, u) {
      var ext = /^https?:|^mailto:/.test(u) ? ' target="_blank" rel="noopener"' : '';
      return '<a href="' + u + '"' + ext + '>' + tt + '</a>';
    });
    s = s.replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>');
    s = s.replace(/(^|[^*])\*([^*\n]+)\*/g, '$1<em>$2</em>');
    return s;
  }

  function splitRow(line) {
    return line.replace(/^\|/, '').replace(/\|$/, '').split('|').map(function (c) { return c.trim(); });
  }

  function mdToHtml(md, imgBase) {
    if (!md) return '';
    var src = String(md).replace(/\r\n?/g, '\n');
    if (imgBase) src = src.replace(/\(images\//g, '(' + imgBase + 'images/');
    var stash = [];
    function put(html) { stash.push(html); return '\u0000' + (stash.length - 1) + '\u0000'; }
    src = src.replace(/```[^\n]*\n([\s\S]*?)(?:```|$)/g, function (_, code) {
      return put('<div class="highlight"><pre><code>' + esc(code.replace(/\n$/, '')) + '</code></pre></div>');
    });
    var codes = [];
    src = src.replace(/`([^`\n]+)`/g, function (_, c) {
      codes.push('<code>' + esc(c) + '</code>');
      return '\u0000c' + (codes.length - 1) + '\u0000';
    });
    src = src.replace(/(^|[^(\[>"'=])(https?:\/\/[^\s<()\[\]]+)/g, function (_, pre, url) {
      var m2 = url.match(/^(.*?)[.,;:!?]+$/);
      var clean = m2 ? m2[1] : url;
      var tail = m2 ? url.slice(clean.length) : '';
      return pre + '[' + clean + '](' + clean + ')' + tail;
    });
    var lines = src.split('\n');
    var out = [], i = 0;
    while (i < lines.length) {
      var tt = lines[i].trim();
      if (tt === '') { i++; continue; }
      if (/^\u0000c?\d+\u0000$/.test(tt)) { out.push(tt); i++; continue; }
      var h = tt.match(/^(#{1,6})\s+(.*)$/);
      if (h) { out.push('<h' + h[1].length + '>' + inline(h[2]) + '</h' + h[1].length + '>'); i++; continue; }
      if (/^(-{3,}|\*{3,})$/.test(tt)) { out.push('<hr>'); i++; continue; }
      if (/^>/.test(tt)) {
        var q = [];
        while (i < lines.length && /^>/.test(lines[i].trim())) { q.push(lines[i].trim().replace(/^>\s?/, '')); i++; }
        out.push('<blockquote><p>' + inline(q.join(' ')) + '</p></blockquote>');
        continue;
      }
      if (/^\|/.test(tt) && i + 1 < lines.length && /^\|[\s:|-]+\|$/.test(lines[i + 1].trim())) {
        var head = splitRow(tt); i += 2;
        var rows = [];
        while (i < lines.length && /^\|/.test(lines[i].trim())) { rows.push(splitRow(lines[i].trim())); i++; }
        out.push('<div class="table-wrap"><table><thead><tr>' + head.map(function (c) { return '<th>' + inline(c) + '</th>'; }).join('') +
          '</tr></thead><tbody>' +
          rows.map(function (r) { return '<tr>' + r.map(function (c) { return '<td>' + inline(c) + '</td>'; }).join('') + '</tr>'; }).join('') +
          '</tbody></table></div>');
        continue;
      }
      if (/^([-*]|\d+\.)\s+/.test(tt)) {
        var ordered = /^\d+\./.test(tt);
        var items = [];
        while (i < lines.length && /^([-*]|\d+\.)\s+/.test(lines[i].trim())) {
          items.push(lines[i].trim().replace(/^([-*]|\d+\.)\s+/, ''));
          i++;
        }
        out.push((ordered ? '<ol>' : '<ul>') + items.map(function (x) { return '<li>' + inline(x) + '</li>'; }).join('') + (ordered ? '</ol>' : '</ul>'));
        continue;
      }
      var par = [tt]; i++;
      while (i < lines.length) {
        var n = lines[i].trim();
        if (n === '' || /^(#{1,6}\s|>|\||[-*]\s|\d+\.\s)/.test(n) || /^(-{3,}|\*{3,})$/.test(n) || /^\u0000c?\d+\u0000$/.test(n)) break;
        par.push(n); i++;
      }
      out.push('<p>' + par.map(inline).join('<br>') + '</p>');
    }
    return out.join('\n')
      .replace(/\u0000c(\d+)\u0000/g, function (_, n) { return codes[+n]; })
      .replace(/\u0000(\d+)\u0000/g, function (_, n) { return stash[+n]; });
  }

