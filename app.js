  function isSkippableImage(img) {
    return Boolean(img.closest('pre, code, .highlighter-rouge'));
  }

  function getImageSize(img) {
    var w = Number.parseInt(img.getAttribute('width') || '', 10);
    var hgt = Number.parseInt(img.getAttribute('height') || '', 10);
    if (Number.isFinite(w) && w > 0 && Number.isFinite(hgt) && hgt > 0) return { width: w, height: hgt };
    if (img.naturalWidth > 0 && img.naturalHeight > 0) return { width: img.naturalWidth, height: img.naturalHeight };
    return { width: 1600, height: 1200 };
  }

  function ensureAnchor(img) {
    var existing = img.closest('a.post-image-link');
    if (existing) return existing;
    var anchor = document.createElement('a');
    anchor.className = 'post-image-link';
    anchor.href = img.currentSrc || img.src;
    img.parentNode.insertBefore(anchor, img);
    anchor.appendChild(img);
    return anchor;
  }

  function ensureAnchorMetadata(anchor) {
    var img = anchor.querySelector('img');
    if (!img) return;
    var imageSrc = img.currentSrc || img.getAttribute('src') || '';
    var imageSrcset = img.getAttribute('srcset') || '';
    var imageSizes = img.getAttribute('sizes') || '100vw';
    var existingHref = anchor.getAttribute('href') || '';
    var existingOriginal = anchor.getAttribute('data-original-src') || '';
    var imgOriginal = img.dataset.originalSrc || '';
    var originalSrc = existingOriginal || imgOriginal || existingHref || imageSrc;
    if (!existingOriginal && originalSrc) anchor.setAttribute('data-original-src', originalSrc);
    if (!existingHref || (existingHref === originalSrc && imageSrc && imageSrc !== originalSrc)) {
      anchor.setAttribute('href', imageSrc || originalSrc);
    }
    if (!anchor.getAttribute('data-pswp-src')) anchor.setAttribute('data-pswp-src', anchor.getAttribute('href') || imageSrc || originalSrc);
    if (!anchor.getAttribute('data-pswp-srcset') && imageSrcset) anchor.setAttribute('data-pswp-srcset', imageSrcset);
    if (!anchor.getAttribute('data-pswp-sizes')) anchor.setAttribute('data-pswp-sizes', imageSizes);
    var size = getImageSize(img);
    anchor.setAttribute('data-pswp-width', String(size.width));
    anchor.setAttribute('data-pswp-height', String(size.height));
  }

  function bootstrapGallery() {
    var anchors = [];
    var images = Array.prototype.slice.call(document.querySelectorAll('.content img'));
    for (var i = 0; i < images.length; i++) {
      var img = images[i];
      if (isSkippableImage(img)) continue;
      var anchor = ensureAnchor(img);
      ensureAnchorMetadata(anchor);
      anchors.push(anchor);
      if (!img.complete) {
        img.addEventListener('load', function () { ensureAnchorMetadata(anchor); }, { once: true });
      }
    }
    return anchors;
  }

  function getCurrentOriginalUrl(pswp) {
    var slide = pswp && pswp.currSlide;
    if (!slide || !slide.data) return '';
    var el = slide.data.element;
    return (el && el.getAttribute('data-original-src'))
      || (el && el.dataset && el.dataset.originalSrc)
      || slide.data.originalSrc || slide.data.src || '';
  }

  var LightboxClass = null;
  var currentLb = null;
  function ensureLightboxClass() {
    if (LightboxClass) return Promise.resolve(LightboxClass);
    return import('https://cdn.jsdelivr.net/npm/photoswipe@5.4.4/dist/photoswipe-lightbox.esm.min.js')
      .then(function (m) { LightboxClass = m.default || null; return LightboxClass; })
      .catch(function () { LightboxClass = null; return null; });
  }

  function initLightbox(seq) {
    var anchors = bootstrapGallery();
    if (currentLb) { try { currentLb.destroy(); } catch (e) {} currentLb = null; }
    if (!anchors.length) return;
    ensureLightboxClass().then(function (cls) {
      if (seq !== renderSeq) return;
      if (!cls) {
        anchors.forEach(function (a) { a.target = '_blank'; a.rel = 'noopener'; });
        return;
      }
      currentLb = new cls({
        gallery: '.content',
        children: 'a.post-image-link',
        preload: [0, 1],
        closeSVG: APPLE_CLOSE_SVG,
        zoomSVG: APPLE_ZOOM_SVG,
        arrowPrevSVG: APPLE_ARROW_PREV_SVG,
        arrowNextSVG: APPLE_ARROW_NEXT_SVG,
        pswpModule: function () { return import('https://cdn.jsdelivr.net/npm/photoswipe@5.4.4/dist/photoswipe.esm.min.js'); }
      });
      currentLb.on('uiRegister', function () {
        currentLb.pswp.ui.registerElement({
          name: 'open-original',
          order: 15,
          isButton: true,
          title: 'View original image',
          ariaLabel: 'View original image in new tab',
          html: APPLE_OPEN_ORIGINAL_SVG,
          onClick: function (_event, _el, pswp) {
            var u = getCurrentOriginalUrl(pswp);
            if (u) window.open(u, '_blank', 'noopener,noreferrer');
          }
        });
      });
      currentLb.init();
    });
  }

  /* ---------------- page style pairs ----------------
     home / post / tags pairs are swapped through the two <link> slots
     in index.html. The new pair is appended after app.css (so its rules
     win the cascade during the overlap) and the previously active pair
     is removed once the new one is in. */

  var PAIRS = {
    home: ['styles/home.css', 'styles/home_mobile.css'],
    post: ['styles/post.css', 'styles/post_mobile.css'],
    tags: ['styles/tags.css', 'styles/tags_mobile.css']
  };
  var curPair = 'home';
  var prevPairEls = null; // the pair currently in <head> after the first swap

  function applyPair(kind) {
    var pair = PAIRS[kind] || PAIRS.home;
    var nd = document.createElement('link');
    nd.rel = 'stylesheet'; nd.media = 'screen and (min-width: 600px)';
    var nm = document.createElement('link');
    nm.rel = 'stylesheet'; nm.media = 'screen and (max-width: 600px)';
    // Keep the pair BEFORE app.css in the cascade: app.css must win ties.
    var anchor = document.querySelector('link[href="app.css"]');
    if (anchor) {
      anchor.parentNode.insertBefore(nd, anchor);
      anchor.parentNode.insertBefore(nm, anchor);
    } else {
      document.head.appendChild(nd); document.head.appendChild(nm);
    }
    nd.href = pair[0]; nm.href = pair[1];
    var od = document.getElementById('page-style-desktop'); if (od) od.remove();
    var om = document.getElementById('page-style-mobile'); if (om) om.remove();
    if (prevPairEls) { prevPairEls.d.remove(); prevPairEls.m.remove(); }
    prevPairEls = { d: nd, m: nm };
    curPair = kind;
  }

  function ensurePair(kind, cb) {
    if (kind === curPair) { cb(); return; }
    var pair = PAIRS[kind] || PAIRS.home;
    // Do NOT wait for the <link> load events: a link whose media query does
    // not match the viewport is fetched lazily (or never), so its load event
    // never fires and the view render would deadlock. Pull the pair through
    // fetch() instead — it always settles — then append the links (which hit
    // the cache) and only then drop the old pair.
    if (typeof fetch === 'function' && location.protocol !== 'file:') {
      Promise.all([fetch(pair[0], { cache: 'force-cache' }),
                   fetch(pair[1], { cache: 'force-cache' })])
        .then(function () { applyPair(kind); cb(); },
              function () { applyPair(kind); cb(); });
    } else {
      applyPair(kind); cb();
    }
  }

  /* ---------------- enhancement scripts ----------------
     Fetched once, re-executed after every render (self-contained IIFEs
     that bind to whatever DOM is present at execution time). */

  var peSrc = null, searchSrc = null;
  function runPe() {
    if (!peSrc) return;
    try { new Function(peSrc)(); } catch (e) { console.warn('post-enhancements failed:', e); }
  }
  function runSearch() {
    if (!searchSrc) return;
    try { new Function(searchSrc)(); } catch (e) { console.warn('search failed:', e); }
  }

  /* ---------------- render + router ---------------- */

  var renderSeq = 0;

  function render(html, bodyClass, kind, after) {
    var seq = ++renderSeq;
    ensurePair(kind, function () {
      if (seq !== renderSeq) return;
      body.className = bodyClass || '';
      body.innerHTML = html;
      window.scrollTo(0, 0);
      if (after) after(seq);
      runSearch();
    });
  }

  function afterPost(seq) {
    runPe();
    initLightbox(seq);
  }

  function switchTab(tab) {
    var m = (location.hash || '').match(/^#\/post\/(.+)$/);
    if (!m) return;
    var p = POST_BY_DIR[decodeURIComponent(m[1])];
    if (!p || !p.docs || !p.docs[tab]) return;
    var seq = renderSeq;
    document.querySelectorAll('.doc-tab').forEach(function (t) {
      t.classList.toggle('active', t.getAttribute('data-tab') === tab);
    });
    var cc = document.getElementById('doc-content');
    if (!cc) return;
    var doc = postBody(p, tab);
    cc.innerHTML = mdToHtml(doc, '../substack/' + p.dir + '/');
    var n = charsOf(doc);
    var mc = document.getElementById('meta-chars'); if (mc) mc.textContent = fmt(n) + '字';
    var mr = document.getElementById('meta-reading'); if (mr) mr.textContent = '预计阅读' + readMin(n) + '分钟';
    runPe();
    initLightbox(seq);
    window.scrollTo(0, 0);
  }

  function route() {
    var h = location.hash || '#/';
    var rest = h.slice(1);
    if (rest.charAt(0) !== '/') {
      var el = document.getElementById(decodeURIComponent(rest));
      if (el) el.scrollIntoView({ behavior: 'smooth' });
      return;
    }
    var parts = rest.slice(1).split('#');
    var segs = parts[0].split('/').filter(Boolean);
    var view = segs[0] || 'home';
    if (view === 'home' || view === 'p') {
      document.title = SITE_NAME;
      render(homeHtml(pageOf(view === 'p' ? segs[1] : '')), '', 'home');
    } else if (view === 'blogs') {
      var name = parts[1] ? decodeURIComponent(parts[1]) : '';
      if (name && !BLOGS.some(function (b) { return b.name === name; })) name = '';
      document.title = SITE_NAME + ' · Blogs';
      render(blogsHtml(name || null), '', 'tags');
    } else if (view === 'summaries') {
      document.title = SITE_NAME + ' · Summaries';
      render(summariesHtml(pageOf(segs[1] || '')), '', 'tags');
    } else if (view === 'post') {
      var dir = decodeURIComponent(segs.slice(1).join('/'));
      var p = POST_BY_DIR[dir];
      if (!p) {
        document.title = SITE_NAME;
        render(homeHtml(), '', 'home');
        return;
      }
      var tab = (p.docs && p.docs.zh) ? 'zh' : 'yuanwen';
      document.title = SITE_NAME + ' · ' + p.title;
      render(postHtml(p, tab), 'post-page', 'post', afterPost);
    } else {
      document.title = SITE_NAME;
      render(homeHtml(), '', 'home');
    }
  }

  document.addEventListener('click', function (e) {
    var t = e.target && e.target.closest ? e.target.closest('.doc-tab') : null;
    if (t) { switchTab(t.getAttribute('data-tab')); return; }
    var a = e.target && e.target.closest ? e.target.closest('a') : null;
    if (!a) return;
    var href = a.getAttribute('href') || '';
    if (href.charAt(0) === '#' && href.charAt(1) !== '/') {
      var el = document.getElementById(decodeURIComponent(href.slice(1)));
      if (el) { e.preventDefault(); el.scrollIntoView({ behavior: 'smooth', block: 'start' }); }
    }
  });

  window.addEventListener('hashchange', route);

  Promise.all([
    fetch('scripts/post-enhancements.js', { cache: 'no-cache' }).then(function (r) { return r.text(); }).catch(function () { return null; }),
    fetch('scripts/search.js', { cache: 'no-cache' }).then(function (r) { return r.text(); }).catch(function () { return null; })
  ]).then(function (res) {
    peSrc = res[0];
    searchSrc = res[1];
    route();
  });
