  function stripDocHeader(md, p) {
    // Strip the leading doc header: the H1 title (原文/中文版/总结) and a
    // directly-glued H2 subtitle; attribute lines (来源/标题/发布日期/
    // 原文链接/说明/链接/主题/整理日期/博客/博客名/翻译整理日期/抓取日期/
    // 关于本文的说明, optionally with an English "/Source"-style suffix;
    // plain, "- " bulleted or "> " quoted, key optionally **bold**); the
    // "本文件为…/关于本文的说明" translator note (quoted continuation
    // lines); one closing "---" separator; and - in Substack captures -
    // the title block after the hero image: H1/H2 lines repeating the
    // post title or blog name, plus the image glued right before one.
    // The post page header already shows title/date/source/原文链接.
    var lines = md.split('\n');
    var n = lines.length;
    var i = 0;
    while (i < n && lines[i].trim() === '') i++;
    var removed = false;
    if (i < n && /^#\s+/.test(lines[i].trim())) {
      i++; removed = true;
      if (i < n && /^##\s+/.test(lines[i].trim())) i++; // glued subtitle
    }
    var metaKey = function (t) {
      t = t.replace(/^>\s*/, '');
      t = t.replace(/^[-*]\s+/, '');
      t = t.replace(/^\*\*(.+?)\*\*\s*[:：]/, '$1:');
      var m = /^(来源|标题|发布日期|原文链接|说明|链接|主题|整理日期|博客|博客名|翻译整理日期|抓取日期|关于本文的说明)(\s*\/\s*[A-Za-z]+)?\s*[:：]/.exec(t);
      return m ? m[1] : null;
    };
    var lat = function (s) { return String(s).toLowerCase().replace(/[^a-z0-9]/g, ''); };
    // The Substack captures repeat the page title block mid-document:
    // hero image, "# BlogName", logo image, "# PostTitle", subtitle.
    // Anchor on the blog name (parenthetical author dropped); the title
    // block then consumes at most one more H1/H2 plus one H2/H3.
    var blogCore = p ? lat(String(p.blog || '').replace(/[（(][^）)]*[）)]/g, '')) : '';
    var titleCore = p ? lat(p.title || '') : '';
    var isAnchor = function (t) {
      if (!/^#{1,2}\s+/.test(t)) return false;
      var hl = lat(t.replace(/^#{1,2}\s+/, ''));
      if (blogCore.length >= 10 && hl.indexOf(blogCore) !== -1) return true;
      if (titleCore.length >= 10 && hl.indexOf(titleCore) !== -1) return true;
      return false;
    };
    var inNote = false;
    while (i < n) {
      var t = lines[i].trim();
      if (t === '') { inNote = false; i++; continue; }
      var k = metaKey(t);
      if (k) {
        i++; removed = true;
        if (k === '关于本文的说明') inNote = true; // multi-line quoted note
        continue;
      }
      if (/^(>)?\s*本文件为/.test(t)) { i++; removed = true; inNote = true; continue; }
      if (inNote && /^>/.test(t)) { i++; continue; }
      if (t === '---' && removed) { i++; continue; }
      if (removed && isAnchor(t)) {
        i++; // blog-name heading (or title heading) starts the title block
        var phase = 2;
        while (i < n) {
          var u = lines[i].trim();
          if (u === '' || u === '---') { i++; continue; }
          if (phase === 2) {
            if (/^!/.test(u)) { i++; continue; } // logo/hero image
            var hm = u.match(/^(#{1,2})\s/);
            if (hm) { i++; phase = 3; continue; } // the post title
          } else {
            if (/^#{2,3}\s/.test(u)) { i++; break; } // the subtitle, then stop
          }
          break;
        }
        continue;
      }
      if (removed && /^!\[/.test(t)) {
        // drop the hero image only when the title block follows it
        var j = i + 1;
        while (j < n && lines[j].trim() === '') j++;
        if (j < n && isAnchor(lines[j].trim())) { i++; continue; }
      }
      break;
    }
    while (i < n && lines[i].trim() === '') i++;
    return lines.slice(i).join('\n');
  }

  function postBody(p, tab) {
    var doc = stripDocHeader((p.docs && p.docs[tab]) || '', p);
    var brief = p.summary || p.oneliner || '';
    // 简要 is rendered as a plain blockquote above the body.
    return brief ? '> ' + brief.replace(/\n+/g, '\n> ') + '\n\n' + doc : doc;
  }

  function postHtml(p, tab) {
    var doc = postBody(p, tab);
    var n = charsOf(doc);
    function tabBtn(t, label) {
      if (t !== 'yuanwen' && !(p.docs && p.docs[t])) return '';
      return '<span class="doc-tab' + (t === tab ? ' active' : '') + '" data-tab="' + t + '">' + label + '</span>';
    }
    return navigatebar()
      + '<div class="post-layout">'
      + '<div class="content-area">'
      + '<div class="title">' + esc(p.title) + '</div>'
      + '<div class="category-area">「<a href="#/blogs#' + encodeURIComponent(p.blog) + '"><div class="category">' + esc(p.blog) + '</div></a>」</div>'
      + '<div class="post-meta">'
      + '<span class="post-meta-item">' + esc(p.date) + '</span>'
      + '<span class="post-meta-item" id="meta-chars">' + fmt(n) + '字</span>'
      + '<span class="post-meta-item post-meta-reading-time" id="meta-reading">预计阅读' + readMin(n) + '分钟</span>'
      + (p.url ? '<a class="post-meta-item" href="' + esc(p.url) + '" target="_blank" rel="noopener">原文链接</a>' : '')
      + '</div>'
      + '<div class="doc-tabs">' + tabBtn('yuanwen', '原文') + tabBtn('zh', '中文版') + tabBtn('summary', '总结') + '</div>'
      + '<div class="content" id="doc-content">' + mdToHtml(doc, '../substack/' + p.dir + '/') + '</div>'
      + '</div>'
      + '</div>'
      + SEARCH_OVERLAY;
  }

